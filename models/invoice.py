"""
Invoice model - generated by Order.
"""
from __future__ import annotations
from typing import TYPE_CHECKING
from datetime import datetime

if TYPE_CHECKING:
    from .order import Order


class Invoice:
    def __init__(self, invoice_id: str, order: Order, amount: float):
        self.invoice_id = invoice_id
        self.order = order
        self.amount = amount
        self.issued_at = datetime.now()
        self.is_paid = False

    def mark_paid(self):
        self.is_paid = True

    def to_dict(self) -> dict:
        return {
            "invoice_id": self.invoice_id,
            "order_id": self.order.order_id,
            "amount": self.amount,
            "issued_at": self.issued_at.isoformat(),
            "is_paid": self.is_paid,
        }

    def __repr__(self):
        return f"<Invoice {self.invoice_id} for Order {self.order.order_id} ${self.amount}>"